use std::{fmt::Write as _, fs, path::Path};

use anyhow::Result;
use serde::Serialize;

use crate::scenarios::Run;

const EXPLORER: &str = "https://testnet.nearblocks.io/txns";

/// Writes a scenario and summary inside its WASM hash directory.
pub fn write(dir: &Path, run: &Run) -> Result<()> {
    let name = serde_json::to_value(run.scenario)?
        .as_str()
        .unwrap_or_default()
        .to_owned();
    write_named(dir, &name, run, run.passed())
}

/// As [`write`], for any record with the same shape. DAO-only records have
/// no objective code hash and use the `dao` directory.
pub fn write_named(dir: &Path, name: &str, record: &impl Serialize, passed: bool) -> Result<()> {
    let record = serde_json::to_value(record)?;
    let build = record["code_hash"].as_str().unwrap_or("dao");
    let dir = dir.join(build);
    fs::create_dir_all(&dir)?;
    fs::write(
        dir.join(format!("{name}.json")),
        serde_json::to_vec_pretty(&record)?,
    )?;
    println!("  {}", if passed { "PASS" } else { "FAIL" });

    let mut runs: Vec<(String, serde_json::Value)> = Vec::new();
    for entry in fs::read_dir(&dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "json") {
            let stem = path
                .file_stem()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned();
            runs.push((stem, serde_json::from_slice(&fs::read(&path)?)?));
        }
    }
    runs.sort_by(|a, b| a.0.cmp(&b.0));
    fs::write(dir.join("RESULTS.md"), render(&runs)?)?;
    Ok(())
}

fn render(runs: &[(String, serde_json::Value)]) -> Result<String> {
    let mut md = String::from(
        "# Results\n\nGenerated by `cargo run -p extents-e2e -- run …`. Balances are \
         Verifier (`mt_balance_of`) balances in the token's base units.\n\n\
         | Scenario | Result | Objective | Verifier balances before → after |\n\
         | --- | --- | --- | --- |\n",
    );
    for (name, run) in runs {
        let checks = run["checks"].as_array().cloned().unwrap_or_default();
        let pass = !checks.is_empty() && checks.iter().all(|c| c["pass"] == true);
        let steps = run["steps"].as_array().cloned().unwrap_or_default();
        // The deploy step has no "before"; use the first step that has one.
        let before = steps
            .iter()
            .map(|s| &s["before"]["mt"])
            .find(|m| m.as_object().is_some_and(|m| !m.is_empty()));
        let after = steps.last().map(|s| &s["after"]["mt"]);
        let balances = before
            .and_then(|b| b.as_object())
            .map(|b| {
                b.iter()
                    .map(|(account, amount)| {
                        let to = after.and_then(|a| a[account].as_str()).unwrap_or("?");
                        format!("`{account}` {} → {to}", amount.as_str().unwrap_or("?"))
                    })
                    .collect::<Vec<_>>()
                    .join("<br>")
            })
            .unwrap_or_default();
        writeln!(
            md,
            "| [{name}](#{name}) | {} | `{}` | {balances} |",
            if pass { "pass" } else { "**fail**" },
            run["objective"].as_str().unwrap_or("-"),
        )?;
    }

    for (name, run) in runs {
        writeln!(
            md,
            "\nBuild for {name}: objective WASM SHA-256 `{}`; Verifier SHA-256 `{}`.",
            run["code_hash"].as_str().unwrap_or("not applicable"),
            run["verifier_sha256"].as_str().unwrap_or("not recorded"),
        )?;
        writeln!(
            md,
            "\n## {name}\n\nStateInit deposit: {} yocto (only missing storage stake is kept; the rest is refunded)\n",
            run["deposit_yocto"]
        )?;
        writeln!(
            md,
            "| Step | Tx | Result | Gas (Tgas) |\n| --- | --- | --- | --- |"
        )?;
        for step in run["steps"].as_array().into_iter().flatten() {
            let failed: Vec<_> = step["receipts"]
                .as_array()
                .into_iter()
                .flatten()
                .filter(|r| r["ok"] == false)
                .map(|r| {
                    format!(
                        "{} on {} failed",
                        r["action"].as_str().unwrap_or("?"),
                        r["executor"].as_str().unwrap_or("?")
                    )
                })
                .collect();
            let result = match step["error"].as_str() {
                Some(err) => format!("failed: {}", err.replace('|', "\\|")),
                None if failed.is_empty() => "ok".into(),
                None => format!("ok; {}", failed.join("; ")),
            };
            let hash = step["hash"].as_str().unwrap_or("?");
            writeln!(
                md,
                "| {} | [{}…]({EXPLORER}/{hash}) | {result} | {:.1} of {:.0} |",
                step["label"].as_str().unwrap_or("?"),
                &hash[..hash.len().min(10)],
                step["burnt_tgas"].as_f64().unwrap_or_default(),
                step["prepaid_tgas"].as_f64().unwrap_or_default(),
            )?;
        }
        writeln!(md, "\n| Check | Result | Detail |\n| --- | --- | --- |")?;
        for check in run["checks"].as_array().into_iter().flatten() {
            writeln!(
                md,
                "| {} | {} | {} |",
                check["name"].as_str().unwrap_or("?"),
                if check["pass"] == true {
                    "pass"
                } else {
                    "**fail**"
                },
                check["detail"].as_str().unwrap_or("").replace('|', "\\|"),
            )?;
        }
    }
    Ok(md)
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn reports_from_different_builds_never_share_a_summary() -> Result<()> {
        let dir = std::env::temp_dir().join(format!("extents-reports-{}", rand::random::<u64>()));
        let record = |code_hash: &str| {
            json!({
                "code_hash": code_hash,
                "verifier_sha256": extents_client::VERIFIER_SHA256,
                "checks": [{ "pass": true }],
                "steps": [],
            })
        };
        write_named(&dir, "first", &record("build-a"), true)?;
        write_named(&dir, "second", &record("build-b"), true)?;
        let a = fs::read_to_string(dir.join("build-a/RESULTS.md"))?;
        let b = fs::read_to_string(dir.join("build-b/RESULTS.md"))?;
        let saved: serde_json::Value =
            serde_json::from_slice(&fs::read(dir.join("build-a/first.json"))?)?;
        fs::remove_dir_all(&dir)?;
        assert!(a.contains("first") && !a.contains("second"));
        assert!(b.contains("second") && !b.contains("first"));
        assert_eq!(saved["code_hash"], "build-a");
        assert_eq!(saved["verifier_sha256"], extents_client::VERIFIER_SHA256);
        Ok(())
    }

    /// A run with a NEAR deposit above `u64::MAX` yocto, as `expired`
    /// records, is written like any other.
    #[test]
    fn writes_a_run_with_a_large_deposit() -> Result<()> {
        use crate::scenarios::{Run, Scenario};

        let dir = std::env::temp_dir().join(format!("extents-reports-{}", rand::random::<u64>()));
        let run = Run {
            code_hash: "build".into(),
            verifier_sha256: extents_client::VERIFIER_SHA256,
            scenario: Scenario::Expired,
            objective: None,
            params: None,
            spec: None,
            reviews: Vec::new(),
            deposit_yocto: 10u128.pow(21).to_string(),
            steps: Vec::new(),
            checks: Vec::new(),
        };
        let written = write(&dir, &run);
        let saved = fs::read(dir.join("build/expired.json"));
        fs::remove_dir_all(&dir).ok();
        written?;
        let saved: serde_json::Value = serde_json::from_slice(&saved?)?;
        assert_eq!(saved["deposit_yocto"], "1000000000000000000000");
        Ok(())
    }
}
